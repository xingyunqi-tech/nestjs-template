def _numeric_options(rng, correct, spread):
    pool = {correct}
    while len(pool) < 4:
        candidate = correct + rng.choice([-1, 1]) * rng.randint(1, spread)
        if candidate > 0:
            pool.add(candidate)
    values = sorted(pool)
    return opts(*[str(v) for v in values]), 'ABCD'[values.index(correct)]


def _generated_s3(count, start):
    rng = random.Random(20261019)
    out = []
    stems = set()
    while len(out) < count:
        n = start + len(out)
        kind = len(out) % 3
        if kind == 0:
            a, d = rng.randint(2, 20), rng.randint(3, 9)
            terms = [a + d * j for j in range(5)]
            stem = '，'.join(map(str, terms)) + '，（　　）'
            correct = a + d * 5
            analysis = f'公差为 {d} 的等差数列，下一项为 {correct}。'
        elif kind == 1:
            base, pct = rng.choice([200, 400, 500, 800]), rng.choice([5, 10, 15, 20, 25])
            correct = base * (100 + pct) // 100
            stem = f'某单位去年有职工 {base} 人，今年比去年增加了 {pct}%，今年该单位有职工（　　）人。'
            analysis = f'{base} × (1 + {pct}%) = {correct}。'
        else:
            v, h = rng.choice([40, 50, 60, 80]), rng.randint(2, 6)
            correct = h
            stem = f'甲、乙两地相距 {v * h} 千米，一辆汽车以每小时 {v} 千米的速度从甲地开往乙地，需要（　　）小时。'
            analysis = f'{v * h} ÷ {v} = {h}。'
        if stem in stems:
            continue
        stems.add(stem)
        options, letter = _numeric_options(rng, correct, max(3, correct // 10))
        out.append(q(f's3-{n:02d}', 'SINGLE', stem, options, letter, analysis))
    return out


